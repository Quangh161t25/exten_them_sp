import {rollup} from 'rollup';
import {fileURLToPath} from 'node:url';

async function writeWithRetry(bundle, options, retries = 5) {
  for (let i = 0; i < retries; i++) {
    try {
      await bundle.write(options);
      return;
    } catch (e) {
      if (i === retries - 1) throw e;
      await new Promise(r => setTimeout(r, 300));
    }
  }
}

const bundle=await rollup({input:fileURLToPath(new URL('../extension/order-tool/dh-sync.js',import.meta.url))});
await writeWithRetry(bundle, {file:'extension/order-tool/dh-sync.bundle.js',format:'iife',name:'DHSheetSync',banner:'// Generated by npm run build:dh. Edit dh-sync.js and shared/dh-sheet.js.'});
await bundle.close();
console.log('Đã build đồng bộ DH');
const finance=await rollup({input:fileURLToPath(new URL('../extension/order-tool/list-finance.js',import.meta.url))});
await writeWithRetry(finance, {file:'extension/order-tool/list-finance.bundle.js',format:'iife',name:'OrderListFinance',banner:'// Generated by npm run build:dh. Edit list-finance.js.'});
await finance.close();
console.log('Đã build tài chính trên danh sách đơn Shopee');
