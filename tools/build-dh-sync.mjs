import {rollup} from 'rollup';
import {fileURLToPath} from 'node:url';
const bundle=await rollup({input:fileURLToPath(new URL('../extension/order-tool/dh-sync.js',import.meta.url))});
await bundle.write({file:'extension/order-tool/dh-sync.bundle.js',format:'iife',name:'DHSheetSync',banner:'// Generated by npm run build:dh. Edit dh-sync.js and shared/dh-sheet.js.'});
await bundle.close();
console.log('Đã build đồng bộ DH');
const finance=await rollup({input:fileURLToPath(new URL('../extension/order-tool/list-finance.js',import.meta.url))});
